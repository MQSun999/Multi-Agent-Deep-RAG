from langchain.tools import tool

@tool
def think_tool(reflection: str) -> str:
    """用于在研究过程中进行战略性反思与决策的工具。

    在每次检索或关键决策节点后调用此工具，对当前进展进行系统性评估。
    此工具为研究流程提供一个刻意的暂停节点，确保决策质量。

    【各智能体使用时机】

    Orchestrator（编排智能体）：
    - 收到用户问题后：此问题是否需要启动研究模式，还是可以直接回答？
    - 拆解主题后：主题划分是否合理、是否覆盖了用户问题的全部关键方面？
    - 研究智能体全部完成后：是否所有主题均已成功检索，可以交给编辑智能体？

    Researcher（研究智能体）：
    - 每次 hybrid_search 后：检索结果是否充分？是否需要调整查询语句？
    - 评估信息缺口时：当前主题还缺少哪些关键信息？
    - 决定是否补充 web_search 时：标准文档库的结果是否已足够，还是需要网络检索补充？
    - 准备写入文件前：收集到的内容是否足以完整回答本主题问题？

    Editor（编辑智能体）：
    - 读取所有研究文件后：各主题内容是否完整，结构是否清晰？
    - 撰写报告前：如何组织内容才能最直接地回答用户的原始问题？

    【反思内容应简洁覆盖以下要点】
    1. 当前已获取的关键信息是什么？
    2. 仍缺少哪些重要信息？
    3. 下一步应采取什么行动？

    注意：反思内容应简明扼要，避免冗长，重点是得出明确的下一步决策。

    Args:
        reflection: 对当前进展、信息缺口及下一步行动的简要反思

    Returns:
        确认反思已记录，供后续决策参考
    """
    return f"反思已记录：{reflection}"


